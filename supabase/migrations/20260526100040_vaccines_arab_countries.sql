insert into public.baby_timeline (kind, age_days, title, body, tips, source_name, source_url, publish_status, country)
select
  'vaccine',
  v.age_days,
  'تطعيمات ' || case v.age_days
    when 0 then 'الولادة'
    when 42 then 'الـ 6 أسابيع'
    when 60 then 'الشهرين'
    when 70 then 'الـ 10 أسابيع'
    when 90 then 'الـ 3 شهور'
    when 98 then 'الـ 14 أسبوع'
    when 120 then 'الـ 4 شهور'
    when 180 then 'الـ 6 شهور'
    when 274 then 'الـ 9 شهور'
    when 330 then 'الـ 11 شهر'
    when 365 then 'السنة'
    when 456 then 'الـ 15 شهر'
    when 548 then 'الـ 18 شهر'
    when 730 then 'السنتين'
  end,
  v.vaccines || '. المواعيد وأسماء التطعيمات ممكن تختلف شوية حسب مكتب الصحة، فامشي على كارت التطعيم بتاع طفلك.',
  array[
    'خدي كارت التطعيم معاكي في كل زيارة',
    'لو عنده سخونية عالية يوم التطعيم اسألي الدكتور قبلها',
    'رضّعيه وخديه في حضنك بعد الحقنة عشان يهدى'
  ],
  'وزارة الصحة — البرنامج الوطني للتحصين (' || c.name || ')',
  'https://immunizationdata.who.int/',
  'review'::public.publish_status,
  v.country
from v
join countries c on c.code = v.country
where not exists (
  select 1 from public.baby_timeline t
   where t.kind = 'vaccine' and t.country = v.country and t.age_days = v.age_days
);

-- النتيجة اللي هتظهر تحت في SQL Editor: عدد التطعيمات لكل بلد (لازم 18 بلد).
select country, count(*) as vaccines,
       count(*) filter (where publish_status = 'published') as published
  from public.baby_timeline
 where kind = 'vaccine'
 group by country
 order by country;
